import { test, expect } from '@playwright/test'
import { readFile, writeFile } from 'node:fs/promises'
import type { Page } from '@playwright/test'

const fixture = 'output/phase9/synthetic.backup.zip'
async function restore(page: Page) {
  await page.goto('/settings')
  await page.getByLabel('Choose a Sheetquo backup (.zip)').setInputFiles(fixture)
  await expect(page.getByText('Backup preview', { exact: true })).toBeVisible()
  await expect(page.getByText(/2 businesses, 2 templates, 2 versions and 2 drafts/)).toBeVisible()
  await page.getByRole('button', { name: 'Restore backup', exact: true }).click()
  await expect(page.getByText(/Restored 2 businesses, 2 templates and 2 drafts/)).toBeVisible()
}

test('clean-profile restore, offline deep links, Excel generation and portable export', async ({ page, context, browser }) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await restore(page)
  await expect(page.getByText('Ready for offline use', { exact: true })).toBeVisible()
  await page.evaluate(() => navigator.serviceWorker.ready)
  await page.reload()
  await expect.poll(() => page.evaluate(() => Boolean(navigator.serviceWorker.controller))).toBe(true)
  await context.setOffline(true)
  await page.goto('/dashboard')
  await page.evaluate(() => document.fonts.ready)
  expect(await page.evaluate(() => document.fonts.check('14px "Inter Variable"'))).toBe(true)
  const manifest = await page.evaluate(async () => (await fetch('/manifest.webmanifest')).json())
  expect(manifest.icons.every((icon: { type: string }) => icon.type === 'image/png')).toBe(true)
  await expect(page.getByRole('heading', { level: 1 })).toBeVisible()
  const quote = page.locator('a[href^="/quotation/"]').filter({ hasNotText: 'New quotation' }).first()
  const href = await quote.getAttribute('href')
  expect(href).not.toContain('/new')
  await page.goto(`${href}?step=generate`)
  const downloadEvent = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Generate Excel', exact: true }).click()
  const download = await downloadEvent
  const path = await download.path()
  const workbook = await readFile(path!)
  expect(workbook.subarray(0, 2).toString()).toBe('PK')
  expect(workbook.byteLength).toBeGreaterThan(5000)
  await page.reload()
  await expect(page.getByRole('button', { name: 'Generate again', exact: true })).toBeEnabled()
  await page.goto('/templates/import')
  await expect(page.getByRole('heading', { level: 1 })).toBeVisible()
  await page.goto('/settings')
  await page.getByLabel('Include quotation drafts', { exact: false }).check()
  const exported = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export backup', exact: true }).click()
  const backup = await exported
  const backupBytes = await readFile((await backup.path())!)
  const cacheURLs = await page.evaluate(async () => {
    const urls: string[] = []
    for (const name of await caches.keys()) for (const request of await (await caches.open(name)).keys()) urls.push(request.url)
    return urls
  })
  expect(cacheURLs.length).toBeGreaterThan(10)
  expect(cacheURLs.every((url) => !/\.(xlsx|zip)(\?|$)|blob:|private\//i.test(url))).toBe(true)
  const fresh = await browser.newContext()
  const freshPage = await fresh.newPage()
  await freshPage.goto(`${test.info().project.use.baseURL}/settings`)
  await expect(freshPage.getByRole('button', { name: 'Export backup', exact: true })).toBeDisabled()
  await freshPage.getByLabel('Choose a Sheetquo backup (.zip)').setInputFiles({ name: 'transfer.backup.zip', mimeType: 'application/zip', buffer: backupBytes })
  await freshPage.getByRole('button', { name: 'Restore backup', exact: true }).click()
  await expect(freshPage.getByText(/Restored 2 businesses, 2 templates and 2 drafts/)).toBeVisible()
  await fresh.close()
  await page.goto('/quotation/new')
  await page.getByRole('textbox', { name: 'Customer’s message', exact: true }).fill('Customer: Offline Sample\nDate: 2026-11-03\n2 pcs Filter @ 100')
  await page.getByRole('button', { name: 'Extract details', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1 })).toContainText('Offline Sample')
  await page.getByRole('link', { name: 'Continue to generate', exact: true }).click()
  const parsedDownload = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Generate Excel', exact: true }).click()
  expect((await parsedDownload).suggestedFilename()).toMatch(/\.xlsx$/)
  expect(errors).toEqual([])
})

test('restore conflicts, explicit replacement, malformed archives and narrow keyboard controls', async ({ page }) => {
  await restore(page)
  await page.getByLabel('Choose a Sheetquo backup (.zip)').setInputFiles(fixture)
  await page.getByLabel('How to restore').selectOption('replace')
  await expect(page.getByRole('button', { name: 'Restore backup', exact: true })).toBeDisabled()
  await page.getByLabel('I saved any backup I need', { exact: false }).check()
  await expect(page.getByRole('button', { name: 'Restore backup', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.getByLabel('Choose a Sheetquo backup (.zip)').setInputFiles(fixture)
  await page.getByLabel('How to restore').selectOption('copy')
  for (const width of [1440, 768, 390]) {
    await page.setViewportSize({ width, height: 900 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.getByRole('heading', { level: 1 }).click()
    await page.evaluate(() => window.scrollTo(0, 0))
    await page.screenshot({ path: `output/phase9/settings-${width}.png`, fullPage: true })
  }
  await page.getByRole('button', { name: 'Restore backup', exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(page.getByText(/Restored 2 businesses, 2 templates and 2 drafts/)).toBeVisible()
  await page.reload()
  await page.getByLabel('Choose a Sheetquo backup (.zip)').setInputFiles({ name: 'broken.zip', mimeType: 'application/zip', buffer: Buffer.from('broken') })
  await expect(page.getByText('This is not a Sheetquo backup file.', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Export backup', exact: true })).toBeEnabled()
})

test('an available update waits for all app windows to close and does not reset the current form', async ({ page, context }) => {
  const original = await readFile('dist/sw.js', 'utf8')
  try {
    await page.goto('/settings')
    await expect(page.getByText('Ready for offline use', { exact: true })).toBeVisible()
    await page.reload()
    await page.getByLabel('Include quotation drafts', { exact: false }).check()
    const second = await context.newPage()
    await second.goto('/settings')
    await writeFile('dist/sw.js', `${original}\n// Phase 9 update lifecycle probe ${Date.now()}\n`)
    await page.evaluate(async () => { const registration = await navigator.serviceWorker.ready; await registration.update() })
    await expect(page.getByText(/An update is ready/)).toBeVisible()
    await expect(page.getByLabel('Include quotation drafts', { exact: false })).toBeChecked()
    expect(await page.evaluate(async () => Boolean((await navigator.serviceWorker.ready).waiting))).toBe(true)
    await page.close()
    expect(await second.evaluate(async () => Boolean((await navigator.serviceWorker.ready).waiting))).toBe(true)
    await second.close()
    const reopened = await context.newPage()
    await reopened.goto('/settings')
    await expect.poll(() => reopened.evaluate(async () => Boolean((await navigator.serviceWorker.ready).waiting))).toBe(false)
    await expect(reopened.getByText('Ready for offline use', { exact: true })).toBeVisible()
  } finally { await writeFile('dist/sw.js', original) }
})
