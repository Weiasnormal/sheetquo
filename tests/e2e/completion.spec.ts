import { test, expect } from '@playwright/test'

test('replacement mapping, duplication, output controls, explicit activation, default and last template, history and terms', async ({ page }) => {
  test.setTimeout(90_000)
  page.setDefaultTimeout(10_000)
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/settings')
  await page.getByLabel('Choose a Sheetquo backup (.zip)').setInputFiles('output/phase9/synthetic.backup.zip')
  await page.getByRole('button', { name: 'Restore backup', exact: true }).click()
  await expect(page.getByText(/Restored 2 businesses, 2 templates and 2 drafts/)).toBeVisible()
  await page.getByRole('button', { name: /^Business:/ }).click()
  await page.getByRole('menuitemradio', { name: 'Demo Parts Supply', exact: true }).click()
  await page.goto('/templates')
  const originalHref = await page.getByRole('link', { name: 'Quotation template', exact: true }).getAttribute('href')
  await page.getByRole('link', { name: 'Quotation template', exact: true }).click()
  await page.getByRole('link', { name: 'Upload redesigned workbook', exact: true }).click()
  // Explicitly selected Demo Parts Supply above; archive ID order is not stable.
  await page.locator('input[type=file]').setInputFiles('output/phase9/parts-template.xlsx')
  await page.getByLabel('Last row', { exact: true }).fill('18')
  await page.getByRole('button', { name: 'Save new workbook version', exact: true }).click()
  await expect(page.getByText(/field mappings kept from matching cell signatures/)).toBeVisible()
  await page.getByRole('combobox', { name: 'Money format', exact: true }).selectOption('business')
  await page.getByRole('combobox', { name: 'Date format', exact: true }).selectOption('iso')
  await page.getByLabel('Minimum item height (pt)', { exact: true }).fill('25')
  await page.getByLabel('Maximum item height (pt)', { exact: true }).fill('300')
  await page.getByRole('button', { name: 'Test template', exact: true }).click()
  await page.getByRole('button', { name: 'Run test', exact: true }).click()
  await expect(page.getByRole('button', { name: /Make.*active/i })).toBeEnabled()
  await page.getByRole('button', { name: /Make.*active/i }).click()
  await expect(page.getByRole('alertdialog')).toBeVisible()
  await page.getByRole('button', { name: 'Confirm activation', exact: true }).click()
  await page.goto(originalHref!)
  await expect(page.getByRole('combobox', { name: 'Date format', exact: true })).toHaveValue('iso')
  await page.getByRole('button', { name: 'Duplicate template', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1 })).toContainText('(copy)')
  await page.getByRole('button', { name: 'Add adjustment row', exact: true }).click()
  await page.getByLabel('Adjustment 1 label cell', { exact: true }).fill('A20')
  await page.getByLabel('Adjustment 1 amount cell', { exact: true }).fill('F20')
  // A partial mapping survives autosave/reload, then can be removed before activation.
  await expect(page.getByText('All changes saved', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('Adjustment 1 amount cell', { exact: true })).toHaveValue('F20')
  await page.getByRole('button', { name: 'Remove adjustment row 1', exact: true }).click()
  await page.getByRole('button', { name: 'Test template', exact: true }).click()
  await page.getByRole('button', { name: 'Run test', exact: true }).click()
  await page.getByRole('button', { name: /Make.*active/i }).click()
  await page.getByRole('button', { name: 'Confirm activation', exact: true }).click()
  await page.goto('/templates')
  const defaultControl = page.getByLabel(/Default template for/)
  const options = await defaultControl.locator('option').allTextContents()
  expect(options).toContain('Quotation template (copy)')
  await defaultControl.selectOption({ label: 'Quotation template (copy)' })
  await expect(page.getByText('Default template saved', { exact: true })).toBeVisible()
  await page.goto('/quotation/new')
  await expect(page.getByRole('combobox', { name: 'Quotation layout', exact: true }).locator('option:checked')).toHaveText('Quotation template (copy) · adaptive')
  await page.getByRole('combobox', { name: 'Quotation layout', exact: true }).selectOption({ label: 'Quotation template · fixed Excel form' })
  await page.reload()
  await expect(page.getByRole('combobox', { name: 'Quotation layout', exact: true }).locator('option:checked')).toHaveText('Quotation template · fixed Excel form')
  await page.goto('/quotations')
  await expect(page.getByText('1 matching quotations')).toBeVisible()
  await page.getByRole('searchbox').fill('missing name')
  await expect(page.getByText('0 matching quotations')).toBeVisible()
  await page.getByRole('searchbox').fill('Demo Customer')
  await page.locator('main a[href^="/quotation/"]').first().click()
  await page.getByRole('textbox', { name: /^Terms/ }).fill('Payment in 30 days')
  await expect(page.getByText('All changes saved', { exact: true }).first()).toBeVisible()
  await page.reload()
  await expect(page.getByRole('textbox', { name: /^Terms/ })).toHaveValue('Payment in 30 days')
  await page.goto('/quotations')
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'output/completion/history-mobile.png', fullPage: true })
  expect(errors).toEqual([])
})
