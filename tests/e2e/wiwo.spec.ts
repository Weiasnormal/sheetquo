test('mobile, zoom, modals and offline replay preserve actual records', async ({ page, context }) => {
  await restore(page)
  await page.goto('/quotations')
  await page.locator('main a[href^="/quotation/"]').first().click()
  const recordURL = page.url()
  const values = await page.locator('main input').evaluateAll((nodes) => nodes.map((node) => (node as HTMLInputElement).value))
  for (const width of [1440, 768, 390]) {
    await page.setViewportSize({ width, height: 900 })
    await chapter(page, 'adjustments')
    await expect(page.locator('.wiwo-highlight')).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    const box = await card(page).boundingBox()
    expect(box!.x).toBeGreaterThanOrEqual(0); expect(box!.x + box!.width).toBeLessThanOrEqual(width)
    await page.screenshot({ path: `output/wiwo/guide-${width}.png`, fullPage: false })
    await page.getByRole('button', { name: 'Cancel Wiwo tutorial', exact: true }).click()
  }
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.evaluate(() => { document.documentElement.style.zoom = '2' })
  await chapter(page, 'details')
  await page.screenshot({ path: 'output/wiwo/guide-zoom.png' })
  await page.getByRole('button', { name: 'Cancel Wiwo tutorial', exact: true }).click()
  await page.evaluate(() => { document.documentElement.style.zoom = '' })
  await page.setViewportSize({ width: 390, height: 900 })
  await chapter(page, 'items')
  await page.getByRole('button', { name: 'Open menu', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('dialog').getByRole('button', { name: 'Cancel Wiwo tutorial', exact: true }).click()
  await page.getByRole('button', { name: 'Close menu', exact: true }).click()
  expect(await page.locator('main input').evaluateAll((nodes) => nodes.map((node) => (node as HTMLInputElement).value))).toEqual(values)
  await page.goto('/settings')
  await expect(page.getByText('Ready for offline use', { exact: true })).toBeVisible()
  await page.reload()
  await expect.poll(() => page.evaluate(() => Boolean(navigator.serviceWorker.controller))).toBe(true)
  await context.setOffline(true)
  await page.goto(recordURL)
  await chapter(page, 'details')
  await expect(card(page).getByRole('heading')).toHaveText('Identify the customer and quotation')
})

