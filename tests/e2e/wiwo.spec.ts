test('a full introductory chapter can be completed using only the keyboard', async ({ page }) => {
  await page.goto('/dashboard')
  await expect(page.getByRole('heading', { level: 1 })).toBeVisible()
  async function tabTo(label: string) {
    for (let tries = 0; tries < 60; tries++) {
      const focused = await page.evaluate((name) => {
        const node = document.activeElement
        return node?.getAttribute('aria-label') === name || (node?.tagName === 'BUTTON' && node.textContent?.trim() === name)
      }, label)
      if (focused) return
      await page.keyboard.press('Tab')
    }
    throw new Error(`Keyboard could not reach ${label}`)
  }
  await tabTo('Wiwo — guide me on this screen')
  await page.keyboard.press('Enter')
  await expect(card(page).getByRole('heading')).toHaveText('Meet Wiwo')
  for (const label of ['Next', 'Next', 'Next', 'Next', 'Got it']) {
    await tabTo(label)
    await page.keyboard.press('Enter')
  }
  await expect(card(page).getByRole('heading')).toHaveText('Chapter complete')
  await tabTo('Done')
  await page.keyboard.press('Enter')
  await expect(card(page)).toHaveCount(0)
})
