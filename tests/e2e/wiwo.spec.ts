import { test, expect, type Page } from '@playwright/test'

test.beforeEach(({ page }) => { page.setDefaultTimeout(10_000) })

const card = (page: Page) => page.getByRole('region', { name: 'Wiwo tutorial', exact: true })
const next = (page: Page) => card(page).getByRole('button', { name: /^(Next|Finish|Got it|I understand.*|Finish chapter)$/ })
async function chapter(page: Page, id: string) {
  if (await page.getByRole('button', { name: 'Cancel Wiwo tutorial', exact: true }).count()) await page.getByRole('button', { name: 'Cancel Wiwo tutorial', exact: true }).click()
  await page.getByRole('button', { name: 'Wiwo — guide me on this screen', exact: true }).click()
  await card(page).getByLabel('Chapter', { exact: true }).selectOption(id)
  await expect(card(page)).toBeVisible()
}
async function forward(page: Page, count: number) { for (let i = 0; i < count; i++) await next(page).click() }
async function room(page: Page) { await card(page).getByRole('button', { name: 'Go to control' }).click() }
async function expand(page: Page) {
  await expect(card(page)).toBeVisible()
  const button = card(page).getByRole('button', { name: 'Show full step' })
  if (await button.count()) await button.click()
}
async function restore(page: Page) {
  await page.goto('/settings')
  await page.getByLabel('Choose a Sheetquo backup (.zip)').setInputFiles('output/phase9/synthetic.backup.zip')
  await page.getByRole('button', { name: 'Restore backup', exact: true }).click()
  await expect(page.getByText(/Restored 2 businesses/)).toBeVisible()
  await page.getByRole('button', { name: /^Business:/ }).click()
  await page.getByRole('menuitemradio', { name: 'Demo Parts Supply', exact: true }).click()
}

